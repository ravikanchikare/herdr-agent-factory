use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use runtime_contract::{CONTRACT_VERSION, named_schemas};
use serde_json::{Map, Value, json};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let check = match std::env::args().nth(1).as_deref() {
        None => false,
        Some("--check") => true,
        Some(argument) => return Err(format!("unknown argument `{argument}`").into()),
    };
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let schema_path = root.join("packages/shared/runtime-client/generated/runtime-ipc.schema.json");
    let typescript_path = root.join("packages/shared/runtime-client/src/generated/runtime-ipc.ts");
    let schema = build_schema()?;
    let schema_text = format!("{}\n", serde_json::to_string_pretty(&schema)?);
    let typescript = build_typescript(&schema)?;
    if check {
        check_file(&schema_path, &schema_text)?;
        check_file(&typescript_path, &typescript)?;
        println!("Runtime IPC contracts are current.");
    } else {
        write_file(&schema_path, &schema_text)?;
        write_file(&typescript_path, &typescript)?;
        println!("Generated runtime IPC JSON Schema and TypeScript bindings.");
    }
    Ok(())
}

fn build_schema() -> Result<Value, Box<dyn std::error::Error>> {
    let mut definitions = BTreeMap::<String, Value>::new();
    for (name, mut schema) in named_schemas() {
        let object = schema
            .as_object_mut()
            .ok_or_else(|| format!("schema for {name} is not an object"))?;
        object.remove("$schema");
        object.remove("title");
        if let Some(Value::Object(nested)) = object.remove("$defs") {
            for (nested_name, nested_schema) in nested {
                insert_definition(&mut definitions, nested_name, nested_schema)?;
            }
        }
        insert_definition(&mut definitions, name.into(), schema)?;
    }
    Ok(json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://agent-factory.local/schemas/runtime-ipc-v1.json",
        "title": "Agent Factory Runtime IPC v1",
        "type": "object",
        "$defs": definitions,
    }))
}

fn insert_definition(
    definitions: &mut BTreeMap<String, Value>,
    name: String,
    schema: Value,
) -> Result<(), Box<dyn std::error::Error>> {
    if let Some(existing) = definitions.get(&name)
        && existing != &schema
    {
        return Err(format!("conflicting generated schema definition `{name}`").into());
    }
    definitions.insert(name, schema);
    Ok(())
}

fn build_typescript(schema: &Value) -> Result<String, Box<dyn std::error::Error>> {
    let definitions = schema
        .get("$defs")
        .and_then(Value::as_object)
        .ok_or("generated schema has no definitions")?;
    let public = named_schemas()
        .keys()
        .map(|name| (*name).to_owned())
        .collect::<BTreeSet<_>>();
    let mut output = format!(
        "// Generated by `cargo run -p runtime-contract --bin generate-runtime-contracts`.\n\
         // Do not edit this file by hand.\n\n\
         export const runtimeProtocolVersion = {CONTRACT_VERSION} as const\n\n"
    );
    for (name, definition) in definitions {
        let export = "export ";
        let generated = typescript_type(definition, 0)?;
        reject_unintended_unknown(name, &generated, public.contains(name))?;
        output.push_str(export);
        output.push_str("type ");
        output.push_str(name);
        output.push_str(" = ");
        output.push_str(&generated);
        output.push_str("\n\n");
    }
    Ok(output)
}

fn reject_unintended_unknown(
    name: &str,
    generated: &str,
    public: bool,
) -> Result<(), Box<dyn std::error::Error>> {
    const INTENTIONALLY_OPAQUE: &[&str] = &["Event", "Frame", "Request", "Response"];
    if public && generated.contains("unknown") && !INTENTIONALLY_OPAQUE.contains(&name) {
        return Err(format!(
            "public wire type `{name}` contains an untyped field; model it explicitly or add a narrowly justified opaque exception"
        )
        .into());
    }
    Ok(())
}

fn typescript_type(schema: &Value, indent: usize) -> Result<String, Box<dyn std::error::Error>> {
    if let Some(allowed) = schema.as_bool() {
        return Ok(if allowed { "unknown" } else { "never" }.into());
    }
    let Some(object) = schema.as_object() else {
        return Err("schema node is not an object".into());
    };
    if let Some(reference) = object.get("$ref").and_then(Value::as_str) {
        let reference = reference
            .rsplit('/')
            .next()
            .ok_or("invalid schema reference")?;
        let mut remainder = object.clone();
        remainder.remove("$ref");
        remove_annotations(&mut remainder);
        if remainder.is_empty() {
            return Ok(reference.into());
        }
        return Ok(format!(
            "{reference} & {}",
            typescript_type(&Value::Object(remainder), indent)?
        ));
    }
    if let Some(constant) = object.get("const") {
        return Ok(typescript_literal(constant));
    }
    if let Some(values) = object.get("enum").and_then(Value::as_array) {
        return Ok(values
            .iter()
            .map(typescript_literal)
            .collect::<Vec<_>>()
            .join(" | "));
    }
    for union in ["oneOf", "anyOf"] {
        if let Some(values) = object.get(union).and_then(Value::as_array) {
            let union_type = values
                .iter()
                .map(|value| typescript_type(value, indent))
                .collect::<Result<Vec<_>, _>>()?
                .join(" | ");
            let mut remainder = object.clone();
            remainder.remove(union);
            remove_annotations(&mut remainder);
            if remainder.is_empty() {
                return Ok(union_type);
            }
            return Ok(format!(
                "({union_type}) & {}",
                typescript_type(&Value::Object(remainder), indent)?
            ));
        }
    }
    if let Some(values) = object.get("allOf").and_then(Value::as_array) {
        return Ok(values
            .iter()
            .map(|value| typescript_type(value, indent))
            .collect::<Result<Vec<_>, _>>()?
            .join(" & "));
    }
    match object.get("type") {
        Some(Value::Array(types)) => Ok(types
            .iter()
            .map(|value| match value.as_str().unwrap_or_default() {
                "array" => object
                    .get("items")
                    .map(|items| typescript_type(items, indent))
                    .transpose()
                    .map(|item| format!("Array<{}>", item.unwrap_or_else(|| "unknown".into()))),
                kind => Ok(primitive_type(kind).into()),
            })
            .collect::<Result<Vec<_>, Box<dyn std::error::Error>>>()?
            .join(" | ")),
        Some(Value::String(kind)) if kind == "object" => object_type(object, indent),
        Some(Value::String(kind)) if kind == "array" => {
            let item = object
                .get("items")
                .map(|value| typescript_type(value, indent))
                .transpose()?
                .unwrap_or_else(|| "unknown".into());
            Ok(format!("Array<{item}>"))
        }
        Some(Value::String(kind)) => {
            if matches!(kind.as_str(), "integer" | "number")
                && object.get("minimum") == object.get("maximum")
                && let Some(value) = object.get("minimum")
            {
                return Ok(value.to_string());
            }
            Ok(primitive_type(kind).into())
        }
        None if object.contains_key("properties") => object_type(object, indent),
        None => Ok("unknown".into()),
        _ => Err("unsupported schema type".into()),
    }
}

fn remove_annotations(object: &mut Map<String, Value>) {
    for key in ["title", "description", "default", "examples", "deprecated"] {
        object.remove(key);
    }
}

fn object_type(
    object: &Map<String, Value>,
    indent: usize,
) -> Result<String, Box<dyn std::error::Error>> {
    let properties = object.get("properties").and_then(Value::as_object);
    let required = object
        .get("required")
        .and_then(Value::as_array)
        .map(|values| {
            values
                .iter()
                .filter_map(Value::as_str)
                .collect::<BTreeSet<_>>()
        })
        .unwrap_or_default();
    if properties.is_none_or(Map::is_empty) {
        return Ok(match object.get("additionalProperties") {
            Some(Value::Object(schema)) => format!(
                "Record<string, {}>",
                typescript_type(&Value::Object(schema.clone()), indent)?
            ),
            Some(Value::Bool(false)) => "Record<string, never>".into(),
            _ => "Record<string, unknown>".into(),
        });
    }
    let padding = " ".repeat(indent);
    let child_padding = " ".repeat(indent + 2);
    let mut output = String::from("{\n");
    for (name, property) in properties.expect("checked above") {
        output.push_str(&child_padding);
        output.push_str(&typescript_property_name(name));
        if !required.contains(name.as_str()) {
            output.push('?');
        }
        output.push_str(": ");
        output.push_str(&typescript_type(property, indent + 2)?);
        output.push('\n');
    }
    output.push_str(&padding);
    output.push('}');
    Ok(output)
}

fn primitive_type(kind: &str) -> &'static str {
    match kind {
        "string" => "string",
        "integer" | "number" => "number",
        "boolean" => "boolean",
        "null" => "null",
        _ => "unknown",
    }
}

fn typescript_literal(value: &Value) -> String {
    match value {
        Value::String(value) => serde_json::to_string(value).expect("string literal"),
        _ => value.to_string(),
    }
}

fn typescript_property_name(name: &str) -> String {
    let mut chars = name.chars();
    let valid = chars
        .next()
        .is_some_and(|first| first == '_' || first == '$' || first.is_ascii_alphabetic())
        && chars.all(|character| {
            character == '_' || character == '$' || character.is_ascii_alphanumeric()
        });
    if valid {
        name.into()
    } else {
        serde_json::to_string(name).expect("property name")
    }
}

fn write_file(path: &Path, content: &str) -> Result<(), Box<dyn std::error::Error>> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, content)?;
    Ok(())
}

fn check_file(path: &Path, expected: &str) -> Result<(), Box<dyn std::error::Error>> {
    let actual = fs::read_to_string(path).map_err(|error| {
        format!(
            "generated contract `{}` is missing: {error}; run the generator",
            path.display()
        )
    })?;
    if actual != expected {
        return Err(format!(
            "generated contract `{}` has drifted; run `cargo run -p runtime-contract --bin generate-runtime-contracts`",
            path.display()
        )
        .into());
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_unknown_in_a_public_wire_type() {
        let error = reject_unintended_unknown("AgentListDto", "{ agents: Array<unknown> }", true)
            .unwrap_err();
        assert!(error.to_string().contains("AgentListDto"));
    }

    #[test]
    fn permits_only_declared_opaque_protocol_fields() {
        reject_unintended_unknown("Event", "{ payload: unknown }", true).unwrap();
        reject_unintended_unknown("PrivateDefinition", "unknown", false).unwrap();
    }
}
